"""
faiss_index.py
--------------
Builds a FAISS index from the item embeddings generated by the Two-Tower model.
This allows extremely fast nearest-neighbor search (candidate retrieval).
"""

from pathlib import Path
import numpy as np
import faiss

ROOT = Path(__file__).resolve().parents[2]
EMBEDDINGS_DIR = ROOT / "data" / "embeddings"
INDEX_DIR = ROOT / "data" / "faiss_index"
INDEX_DIR.mkdir(parents=True, exist_ok=True)


def build_faiss_index():
    print("=" * 60)
    print("Building FAISS Index")
    print("=" * 60)

    # Load embeddings and IDs
    embeddings = np.load(EMBEDDINGS_DIR / "item_embeddings.npy").astype("float32")
    item_ids = np.load(EMBEDDINGS_DIR / "item_ids.npy", allow_pickle=True)

    print(f"Loaded embeddings : {embeddings.shape}")
    print(f"Number of items   : {len(item_ids)}")

    # L2 normalize (recommended for cosine similarity with inner product)
    faiss.normalize_L2(embeddings)

    dimension = embeddings.shape[1]

    # Use IndexFlatIP (Inner Product) for exact search
    # For larger scale you can switch to IVF or HNSW later
    index = faiss.IndexFlatIP(dimension)

    # Add vectors to the index
    index.add(embeddings)

    print(f"FAISS index built. Total vectors: {index.ntotal}")

    # Save index and the mapping of row → movie_id
    faiss.write_index(index, str(INDEX_DIR / "item_index.faiss"))
    np.save(INDEX_DIR / "item_ids.npy", item_ids)

    print(f"\nIndex saved to: {INDEX_DIR / 'item_index.faiss'}")
    print("FAISS index ready!")


if __name__ == "__main__":
    build_faiss_index()